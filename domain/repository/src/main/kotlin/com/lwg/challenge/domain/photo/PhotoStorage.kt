package com.lwg.challenge.domain.photo

/**
 * 인증 사진 저장 포트 (ADR-0011 §2 — challenge-verification T-B1).
 *
 * 구현체는 `:infra:external` 의 `LocalDiskPhotoStorage`. 호스팅이 정해지면 **구현체만 교체**한다.
 * `NotificationSender` ↔ `FcmNotificationSender`/`NoOpNotificationSender` 와 같은 구조다.
 *
 * ## 🔴 앱은 사진을 multipart 로 서버에 직접 올리고, 서버가 저장까지 한 번에 한다
 *
 * ADR-0011 §3(URL 발급 방식)은 2026-08-18 결정으로 **superseded** 됐다. 릴리즈 전이라 호환
 * 제약이 없고 현재 규모(1:1, 하루 1~2장)에서 URL 발급의 이득이 0 이었다 — 3단계 왕복과
 * 만료·재발급 복잡도만 남았다.
 *
 * ## 🔴 이 포트는 URL 을 만들지 않는다 — 조회도 서명 URL 을 폐기했다 (2026-08-18 2차 결정)
 *
 * ADR-0011 §4 의 원칙(*"접근 제어는 서버가 한다"*)은 유지하되 **수단이 바뀌었다**: 서비스가
 * **요청 시점에 JWT 로 당사자를 판정**하고, 이 포트는 바이트를 주고받기만 한다. 서명 URL 의
 * 폐기 근거였던 *"이미지 로더에 인증 헤더를 심는 복잡도"* 는 성립하지 않는 것으로 확인됐다 —
 * Coil 3 `coil-network-ktor3` 가 앱의 기존 인증 `HttpClient` 를 그대로 받는다.
 *
 * 서명 검증 + 바이트 서빙을 맡던 `SelfHostedPhotoEndpoint` 포트는 함께 사라졌다 — 서명이
 * 사라지면 남는 일은 **바이트 읽기뿐**이고 그건 [read] 하나로 충분하다. 원래의 분리 근거
 * (*"이사하면 그쪽은 통째로 사라진다"*)도 더는 성립하지 않는다 — 이사해도 서버는 중계([read])
 * 하거나 302(서명 URL 재도입) 중 하나를 하므로 이 포트가 계속 산다.
 *
 * > ⚠️ 인지된 트레이드오프: 지금은 **서버가 바이트를 중계**한다. 오브젝트 스토리지로 이사한 뒤
 * > 중계가 부담이 되면 이 포트에 서명 URL 발급을 되살려 컨트롤러가 **302 리다이렉트**하면
 * > 되고, **앱은 무변경**이다. 지금 규모(1:1, 하루 1~2장)에서 중계 비용은 문제가 되지 않는다.
 *
 * ## 🔴 접근 제어는 이 포트가 하지 않는다
 *
 * *"이 사람이 이 챌린지의 당사자인가"* 는 **서비스가 판정한다** (ADR-0011 §4). 자체 JWT 라
 * 스토리지의 규칙 엔진으로는 알 수 없기 때문이다. 이 포트는 **당사자 검사를 통과한 뒤에만**
 * 호출된다.
 */
interface PhotoStorage {

    /**
     * 바이트를 저장하고 **서버가 만든 key** 를 돌려준다. 부를 때마다 새 key.
     *
     * 🔴 **사용자 입력이 key 에 들어가지 않는다.** photoKey 생성은 완전히 서버 내부 사정이고
     * 앱은 key 를 보지도 못한다. 경로 탈출(`../`)이나 남의 사진 덮어쓰기가 형태상 불가능하다.
     *
     * key 의 안전한 모양은 저장소마다 다르므로(파일시스템이면 경로, 오브젝트 스토리지면
     * 오브젝트 키) 생성도 이 포트 안에서 한다 — 서비스가 만들면 그 지식이 도메인으로 샌다.
     */
    fun store(challengeId: Long, userId: Long, bytes: ByteArray): String

    /** [key] 의 바이트. 없으면 null. */
    fun read(key: String): ByteArray?

    /**
     * [key] 의 사진을 지운다. 없으면 아무 일도 하지 않는다.
     *
     * 호출부는 **회원탈퇴 하나뿐이다** (mypage T-B2 — `WithdrawalService`). ADR-0011 이 남긴
     * *"보관 기간 — 챌린지 종료 후 삭제 여부"* 는 여전히 범위 밖이고(spec §1 "제외 — 별도 결정
     * 필요"), 탈퇴는 보관 정책이 아니라 **개인정보 삭제** 라는 다른 축에서 여기를 부른다.
     *
     * ⚠️ **트랜잭션이 아니다.** 롤백돼도 지워진 파일은 돌아오지 않으므로 호출자는 반드시
     * **커밋 후에** 불러야 한다. 근거는 `WithdrawalService` KDoc 참조.
     */
    fun delete(key: String)
}
